import type { AppLanguage } from '../types/dank';

export const LANG_STORAGE_KEY = 'dank_lang';
export const DEFAULT_LANGUAGE: AppLanguage = 'ar';

export function getStoredLanguage(): AppLanguage {
  try {
    const val = localStorage.getItem(LANG_STORAGE_KEY);
    if (val === 'en' || val === 'ar') return val;
  } catch {
    // ignore storage access issues
  }
  return DEFAULT_LANGUAGE;
}

export function applyDocumentLanguage(lang: AppLanguage): void {
  if (typeof document === 'undefined') return;
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === 'ar' ? 'rtl' : 'ltr';
  if (lang === 'ar') {
    html.classList.add('font-arabic');
    html.classList.remove('font-english');
  } else {
    html.classList.add('font-english');
    html.classList.remove('font-arabic');
  }
}

